export const LOOKALIKE: Record<string, string[]> = {};
for (const set of SETS) {
  const chars = Array.from(set);
  for (const c of chars) {
    const cur = (LOOKALIKE[c] ||= []);
    for (const x of chars) if (x !== c && !cur.includes(x)) cur.push(x);
  }
}
